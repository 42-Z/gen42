/** Модель агента Турбо в подписке ChatGPT (проверяется кнопкой «Проверить» в админке) */
export const TURBO_AGENT_MODEL = "gpt-6-luna";
/** Верхняя граница ходов агента; обычный прогон — 2–4 раунда */
export const TURBO_MAX_STEPS = 12;
/**
 * Бюджет агента: абсолютный дедлайн на вызовы модели внутри воркфлоу. Не лимит
 * платформы: каждый вызов модели идёт своим шагом (лимит функции 300 с на шаг), а
 * общего потолка на прогон у Workflow нет. Обычно 40–110 с на `high`, около 270 с на
 * `xhigh` и около 340 с на `max`. Вместе с рисованием (до 270 с) и очередью прогон
 * доходит до ~13–14 минут: ожидание страницы (`TURBO_CLIENT_WAIT_MS`) и срок
 * закрытия зависших (`GENERATION_STALE_MS`) обязаны быть больше этой суммы, а
 * порядок «худший прогон < ожидание страницы < закрытие зависших» проверяет
 * `turbo-budgets.test.ts`.
 */
export const TURBO_AGENT_TIMEOUT_MS = 500_000;
/**
 * Сколько страница ждёт результат Турбо опросом, прежде чем сдаться. Больше худшего
 * прогона (агент + рисование + очередь), но меньше срока закрытия зависших на
 * сервере: иначе страница сдавалась бы раньше конца живой генерации, а потом
 * показывала бы возврат кредитов.
 */
export const TURBO_CLIENT_WAIT_MS = 15 * 60_000;
/**
 * Бюджет рисования: запрос к Codex обрывается сам раньше, чем платформа убьёт
 * функцию на лимите 300 с. Шаг делит лимит с предыдущей работой того же вызова
 * `flow`, поэтому у функции задан `WORKFLOW_V2_TIMEOUT_MS` (scripts/build-vercel.ts):
 * рисование стартует в свежем вызове со смещением в несколько секунд, а запас до
 * 300 с остаётся на разбор ответа и запись событий
 */
export const TURBO_DRAW_TIMEOUT_MS = 270_000;
/** Копия изображения для агента: длинная сторона в пикселях и качество WebP */
export const TURBO_PREVIEW_SIZE = 1024;
export const TURBO_PREVIEW_QUALITY = 80;
/** Сколько отказов проверки generateImage подряд допускается: первый вызов и два исправления */
